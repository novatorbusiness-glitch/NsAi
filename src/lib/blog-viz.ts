// Схемы внутри статей (16.10): отметка [[viz:имя]] в тексте статьи → готовый HTML.
// Только цифры и шаги из самой статьи; схема дублирует смысл текста, а не добавляет новые факты.
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

// «Сколько стоит MVP»: три пути к одной первой версии.
const mvp = () => {
	const rows = [
		{ who: "Студия", sum: "0,26–4,4 млн ₽", time: "3–5 месяцев", note: "команда и документация, но долго и дорого", w: 100 },
		{ who: "Разработчик на почасовке", sum: "от 160 тыс. ₽ в месяц", time: "пока идёт работа", note: "без дизайна и без того, кто думает о продукте", w: 38 },
		{ who: "Сами с нейросетями", sum: "несколько тысяч ₽ в месяц", time: "недели или месяцы", note: "платите временем; без порядка шагов дольше", w: 6 },
	];
	return `<figure class="bviz bviz-mvp"><p class="bviz-l">Три пути к одной первой версии</p>${rows
		.map((r) => `<div class="bm-row"><p class="bm-who">${esc(r.who)}<small>${esc(r.time)}</small></p><div class="bm-bar"><i style="width:${r.w}%"></i></div><p class="bm-sum">${esc(r.sum)}<small>${esc(r.note)}</small></p></div>`)
		.join("")}<figcaption>Во всех трёх случаях сначала стоит ответить на один вопрос: будут ли клиенты платить. Длина полосы показывает порядок суммы, не точную цену.</figcaption></figure>`;
};

// «Доверие за 7 касаний»: цепочка шагов, у каждого своя задача из четырёх элементов доверия.
const chain = () => {
	const kind: Record<string, string> = { p: "проблема", e: "экспертность", r: "результат", o: "продукт" };
	const steps: [string, string][] = [
		["p", "Полезный пост о типичной ошибке аудитории, где читатель узнаёт себя"],
		["e", "Чек-лист «как принять ремонт у бригады» в обмен на контакт"],
		["e", "Письмо с кейсом и цифрами"],
		["p", "Разбор, почему старые способы перестали работать и сколько стоит ничего не менять"],
		["r", "История клиента, от «всё разваливалось» до результата"],
		["o", "Как устроена работа изнутри, что в неё входит и кому она не подойдёт"],
		["o", "Предложение с честной причиной решить сейчас"],
	];
	return `<figure class="bviz bviz-chain"><p class="bviz-l">Цепочка из семи касаний</p><ol>${steps
		.map(([k, t], i) => `<li class="k-${k}"><span class="bc-n">${i + 1}</span><div><span class="bc-k">${kind[k]}</span><p>${esc(t)}</p></div></li>`)
		.join("")}</ol><figcaption>Цвет показывает, какую часть доверия закрывает шаг. В одном сообщении одна задача.</figcaption></figure>`;
};

// «Как создать ИИ-агента»: шесть шагов из статьи, цвет — о чём шаг.
const agent = () => {
	const steps: [string, string, string][] = [
		["p", "зачем", "Одна задача, которая съедает ваши часы, и ответ на вопрос «что изменится»"],
		["e", "кто он", "Роль как для нового сотрудника: что делает и чего не делает никогда"],
		["e", "что знает", "Клиенты, прайс, частые вопросы и примеры удачных ответов"],
		["r", "инструкция", "Нейросеть сначала задаёт вам вопросы и собирает скелет"],
		["r", "проверка", "Кто принимает результат, пока агент учится на своих ошибках"],
		["o", "где работает", "Claude Code или Hermes и DeepSeek, файлы и память у вас"],
	];
	return `<figure class="bviz bviz-chain"><p class="bviz-l">Шесть шагов к своему ИИ-агенту</p><ol>${steps
		.map(([k, b, t], i) => `<li class="k-${k}"><span class="bc-n">${i + 1}</span><div><span class="bc-k">${esc(b)}</span><p>${esc(t)}</p></div></li>`)
		.join("")}</ol><figcaption>Программировать не нужно ни на одном шаге: роль, знания и правила пишутся обычным языком.</figcaption></figure>`;
};

// «ИИ-сотрудник для бизнеса»: что отдать агентам и что оставить людям — списки из статьи.
const split = () => {
	const ai = ["Ответы на типовые вопросы по базе знаний", "Разбор переписки, звонков и сделок в CRM", "Посты, рассылки, статьи и коммерческие предложения", "Анализ конкурентов, цен и отзывов", "Черновики счетов, актов и договоров"];
	const hum = ["Что и по какой цене предлагать", "Обещания клиентам: скидки, сроки, договорённости", "Подпись финальных документов", "Решение, кого нанимать", "Ответственность за результат"];
	const col = (cls: string, h: string, xs: string[]) => `<div class="bs-c ${cls}"><p class="bs-h">${h}</p><ul>${xs.map((x) => `<li>${esc(x)}</li>`).join("")}</ul></div>`;
	return `<figure class="bviz bviz-split"><p class="bviz-l">ИИ-сотрудник в команде: кто что делает</p><div class="bs">${col("ai", "Отдать ИИ-агентам", ai)}${col("hum", "Оставить людям", hum)}</div><figcaption>Правило простое: если ошибка стоит денег или доверия клиента, последнее слово за человеком.</figcaption></figure>`;
};

